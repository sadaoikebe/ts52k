#!/usr/bin/env python3
"""Write tc52.pretty/ecs_pad_edge.kicad_mod: ecs_pad with the guard ring cut off at x = +CUT mm.

MX74 sits 8.33 mm from the right board edge; the uncut ring (outer radius 8.5 mm) ends 0.08 mm from the edge.
Electrodes are unchanged; only the ring loses the sliver east of x = +7.8 (0.53 mm from the edge).
"""
import math, os, re
HERE = os.path.dirname(os.path.abspath(__file__))
LIB = os.path.join(os.path.dirname(HERE), 'tc52.pretty')
CUT, RO, RI, AX = 7.8, 8.5, 7.0, -7.75      # AX: pad anchor x (west side of the ring)

def half(sign):
    th = math.acos(CUT / RO)
    pts = []
    n = 40
    for i in range(n + 1):                   # outer arc: th .. pi
        a = th + (math.pi - th) * i / n
        pts.append((RO * math.cos(a), sign * RO * math.sin(a)))
    for i in range(n + 1):                   # inner arc: pi .. 0
        a = math.pi * (1 - i / n)
        pts.append((RI * math.cos(a), sign * RI * math.sin(a)))
    pts.append((CUT, 0.0))
    return pts

def poly(pts):
    xy = ' '.join(f'(xy {x - AX:.4f} {y:.4f})' for x, y in pts)
    return f'(gr_poly (pts {xy}) (width 0) (fill yes))'

s = open(os.path.join(LIB, 'ecs_pad.kicad_mod')).read()
s = s.replace('(footprint "ecs_pad"', '(footprint "ecs_pad_edge"', 1)
s = s.replace('3=guard ring.', '3=guard ring, cut at x=+7.8 mm for the key next to the board edge (generated by tc52-build/gen_edge_fp.py).')
i = s.index('(pad "3"')
j = s.index('(embedded_fonts', i)
pad = f'''(pad "3" smd custom
		(at {AX} 0)
		(size 0.5 0.5)
		(layers "F.Cu")
		(zone_connect 2)
		(options (clearance outline) (anchor rect))
		(primitives
			{poly(half(1))}
			{poly(half(-1))}
			(gr_line (start {-AX} 8) (end {-AX} -8) (width 0.4))
		)
		(uuid "349b8298-fa9a-41f7-ac61-70841c5a2e74")
	)
	'''
s = s[:i] + pad + s[j:]
open(os.path.join(LIB, 'ecs_pad_edge.kicad_mod'), 'w').write(s)
print('wrote ecs_pad_edge')
