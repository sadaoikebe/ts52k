def diag_start(net,far,old,newx):
    # 既存の45度線分(far-old)のold側端点を、同じ直線上のx=newxへ移す。実座標から計算して返す。
    r=e.find(net,far,old); assert len(r)==1
    t=r[0]; pts=[t.GetStart(),t.GetEnd()]
    f=[q for q in pts if e._eq(q,far)][0]
    fx,fy=f.x/1e6,f.y/1e6
    new=(newx,round(fy-(fx-newx),6))
    e.setend(net,far,old,new); return new
